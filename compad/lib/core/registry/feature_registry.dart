class CompadFeature {
  final String id;
  final String title;
  final String subtitle;
  final FeatureCategory category;
  final IconData icon;
  final String route;
  final List<String> keywords;
  final bool isQuickAdd;
  final String? quickAddLabel;
  final bool isOfflineSupported;
  final bool requiresRemoteSync;

  const CompadFeature({
    required this.id,
    required this.title,
    required this.subtitle,
    required this.category,
    required this.icon,
    required this.route,
    required this.keywords,
    this.isQuickAdd = false,
    this.quickAddLabel,
    this.isOfflineSupported = true,
    this.requiresRemoteSync = false,
  });
}

