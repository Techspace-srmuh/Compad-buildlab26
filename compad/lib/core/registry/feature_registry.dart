  static List<CompadFeature> getByCategory(FeatureCategory category) {
    return allFeatures.where((f) => f.category == category).toList();
  }

  static List<CompadFeature> search(String query) {
    final clean = query.trim().toLowerCase();
    if (clean.isEmpty) return allFeatures;
    return allFeatures.where((f) {
      if (f.title.toLowerCase().contains(clean)) return true;
      if (f.subtitle.toLowerCase().contains(clean)) return true;
      return f.keywords.any((k) => k.toLowerCase().contains(clean));
    }).toList();
  }

  static List<CompadFeature> get quickAddFeatures {
    return allFeatures.where((f) => f.isQuickAdd).toList();
  }
